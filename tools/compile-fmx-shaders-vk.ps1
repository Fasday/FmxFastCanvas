using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

public class FmxVar
{
    public string Name, Kind;
    public int Index, Size;
}

public class FmxShader
{
    public string Unit, Name, Kind, DxArch;
    public byte[] Glsl;
    public List<FmxVar> GlslVars = new List<FmxVar>();
    public List<FmxVar> DxVars = new List<FmxVar>();
    public string Vulkan;
    public int BlockSize;
    public uint InputMask;
    public List<string> Notes = new List<string>();
}

public static class FmxGlsl
{
    static readonly Regex RegisterRe = new Regex(@"RegisterShaderFromData\('([^']+)',\s*TContextShaderKind\.(\w+)");
    static readonly Regex SourceRe = new Regex(
        @"TContextShaderSource\.Create\(\s*TContextShaderArch\.(\w+)\s*,\s*\[([^\]]*)\]\s*,\s*\[(.*?)\]\s*\)",
        RegexOptions.Singleline);
    static readonly Regex VarRe = new Regex(
        @"TContextShaderVariable\.Create\('([^']+)',\s*TContextShaderVariableKind\.(\w+),\s*(\d+),\s*(\d+)\)");
    static readonly Regex ByteRe = new Regex(@"\$([0-9A-Fa-f]{2})");

    public static readonly string[] Attributes = { "a_Position", "a_Normal", "a_Color", "a_Color1", "a_Color2",
        "a_Color3", "a_TexCoord0", "a_TexCoord1", "a_TexCoord2", "a_TexCoord3" };

    public static List<FmxShader> Parse(string unit, string text)
    {
        var result = new List<FmxShader>();
        var regs = RegisterRe.Matches(text);
        for (int i = 0; i < regs.Count; i++)
        {
            int start = regs[i].Index;
            int end = i + 1 < regs.Count ? regs[i + 1].Index : text.Length;
            string block = text.Substring(start, end - start);
            var s = new FmxShader { Unit = unit, Name = regs[i].Groups[1].Value, Kind = regs[i].Groups[2].Value };
            var sources = new Dictionary<string, Match>();
            foreach (Match m in SourceRe.Matches(block))
                if (!sources.ContainsKey(m.Groups[1].Value))
                    sources[m.Groups[1].Value] = m;
            if (!sources.ContainsKey("GLSL"))
                continue;
            s.Glsl = ByteRe.Matches(sources["GLSL"].Groups[2].Value).Cast<Match>()
                .Select(b => Convert.ToByte(b.Groups[1].Value, 16)).ToArray();
            s.GlslVars = Vars(sources["GLSL"].Groups[3].Value);
            foreach (var arch in new[] { "DX11", "DX10", "DX11_level_9" })
                if (sources.ContainsKey(arch))
                {
                    s.DxArch = arch;
                    s.DxVars = Vars(sources[arch].Groups[3].Value);
                    break;
                }
            result.Add(s);
        }
        return result;
    }

    static List<FmxVar> Vars(string text)
    {
        return VarRe.Matches(text).Cast<Match>().Select(m => new FmxVar { Name = m.Groups[1].Value,
            Kind = m.Groups[2].Value, Index = int.Parse(m.Groups[3].Value), Size = int.Parse(m.Groups[4].Value) })
            .ToList();
    }

    public static ulong Fnv(byte[] data, ulong hash = 14695981039346656037UL)
    {
        unchecked
        {
            foreach (byte b in data)
            {
                hash ^= b;
                hash *= 1099511628211UL;
            }
        }
        return hash;
    }

    /// <summary>The hash of the Direct3D variables as TFastContext3DVk computes it: per variable its name (UTF-16
    /// code units, upper case), its kind as an ordinal of TContextShaderVariableKind, its index and size.</summary>
    public static ulong VarHash(List<FmxVar> vars)
    {
        var kinds = new[] { "Float", "Float2", "Float3", "Vector", "Matrix", "Texture" };
        ulong h = 14695981039346656037UL;
        foreach (var v in vars)
        {
            var bytes = new List<byte>();
            foreach (char c in v.Name.ToUpperInvariant())
            {
                bytes.Add((byte)(c & 0xFF));
                bytes.Add((byte)(c >> 8));
            }
            int kind = Array.IndexOf(kinds, v.Kind);
            if (kind < 0)
                throw new Exception("unknown variable kind " + v.Kind);
            foreach (int n in new[] { kind, v.Index, v.Size })
                bytes.AddRange(BitConverter.GetBytes(n));
            h = Fnv(bytes.ToArray(), h);
        }
        return h;
    }

    class Struct
    {
        public List<Tuple<string, string, int>> Members = new List<Tuple<string, string, int>>();   // type, name, count
    }

    static void TypeLayout(string type, Dictionary<string, Struct> structs, out int size, out int align)
    {
        switch (type)
        {
            case "float": size = 4; align = 4; return;
            case "vec2": size = 8; align = 8; return;
            case "vec3": size = 12; align = 16; return;
            case "vec4": size = 16; align = 16; return;
            case "mat4": size = 64; align = 16; return;
        }
        Struct st;
        if (!structs.TryGetValue(type, out st))
            throw new Exception("uniform of type " + type);
        int offset = 0;
        align = 16;
        foreach (var m in st.Members)
        {
            int ms, ma;
            MemberLayout(m.Item1, m.Item3, structs, out ms, out ma);
            offset = (offset + ma - 1) / ma * ma + ms;
        }
        size = (offset + 15) / 16 * 16;
    }

    static void MemberLayout(string type, int count, Dictionary<string, Struct> structs, out int size, out int align)
    {
        int es, ea;
        TypeLayout(type, structs, out es, out ea);
        if (count <= 0)
        {
            size = es;
            align = ea;
            return;
        }
        int stride = (es + 15) / 16 * 16;
        size = stride * (count - 1) + es;
        align = 16;
    }

    /// <summary>Offsets of the leaves of a uniform, by the names FMX gives them (Lights[1].Pos, MVPMatrix), relative to
    /// the uniform.</summary>
    static void Leaves(string name, string type, int count, Dictionary<string, Struct> structs,
        Dictionary<string, int> leaves, int baseOffset)
    {
        int es, ea;
        TypeLayout(type, structs, out es, out ea);
        int stride = (es + 15) / 16 * 16;
        Struct st;
        bool isStruct = structs.TryGetValue(type, out st);
        int n = Math.Max(count, 1);
        if (!isStruct)
        {
            leaves[name] = baseOffset;
            return;
        }
        for (int i = 0; i < n; i++)
        {
            string prefix = count > 0 ? name + "[" + i + "]" : name;
            int offset = 0;
            foreach (var m in st.Members)
            {
                int ms, ma;
                MemberLayout(m.Item1, m.Item3, structs, out ms, out ma);
                offset = (offset + ma - 1) / ma * ma;
                Leaves(prefix + "." + m.Item2.TrimStart('_'), m.Item1, m.Item3, structs, leaves,
                    baseOffset + i * stride + offset);
                offset += ms;
            }
        }
    }

    static readonly Regex StructRe = new Regex(@"struct\s+(\w+)\s*\{([^}]*)\};");
    static readonly Regex MemberRe = new Regex(@"(\w+)\s+(\w+)\s*(?:\[(\d+)\])?\s*;");
    static readonly Regex AttributeRe = new Regex(@"^attribute\s+(\w+)\s+(\w+)\s*;\s*$");
    static readonly Regex VaryingRe = new Regex(@"^varying\s+(\w+)\s+(\w+)\s*;\s*$");
    static readonly Regex SamplerRe = new Regex(@"^uniform\s+sampler2D\s+(\w+)\s*;\s*$");
    static readonly Regex UniformRe = new Regex(@"^uniform\s+(\w+)\s+(\w+)\s*(?:\[(\d+)\])?\s*;\s*$");

    /// <summary>Where FMX's GLSL computes otherwise than its Direct3D bytecode (fxc /dumpbin): flips of y for
    /// OpenGL's textures (Vulkan takes Direct3D's coordinates), a saturation Cg lerped with the red component only,
    /// a color left uninitialized. Shader, pattern, replacement, matches expected.</summary>
    static readonly string[][] Patches = {
        new[] { "crop.fps", @"_newCoord = vec2\(TEX0\.x, 1\.0 - TEX0\.y\);", "_newCoord = TEX0.xy;", "1" },
        new[] { "crop.fps", @"\n\s*_newCoord = vec2\(_newCoord\.x, 1\.0 - _newCoord\.y\);", "", "1" },
        new[] { "affine.fps", @"_newCoord = vec2\(TEX0\.x, 1\.0 - TEX0\.y\);", "_newCoord = TEX0.xy;", "1" },
        new[] { "affine.fps", @"vec2\((_newval\w+)\.x, 1\.0 - \1\.y\)", "$1", "1" },
        new[] { "Reflection.fps", @"\(1\.0 - TEX0\.y\)/_Length", "TEX0.y/_Length", "1" },
        new[] { "SwipeFlatTransition.fps", @"\n\s*(_SomePoint\w+)\.y = 1\.0 - \1\.y;", "", "3" },
        new[] { "Bloom.fps", @"(\w+) = (\w+) \+ (\w+)\*\((\w+)\.x - \2\);\n(\s*)(\w+) = vec3\(\1, \1, \1\)\*(\w+);",
            "$6 = (vec3($2) + $3*($4 - vec3($2)))*$7;", "2" },
        new[] { "Gloom.fps", @"(\w+) = (\w+) \+ (\w+)\*\((\w+)\.x - \2\);\n(\s*)(\w+) = vec3\(\1, \1, \1\)\*(\w+);",
            "$6 = (vec3($2) + $3*($4 - vec3($2)))*$7;", "2" },
        new[] { "BrightTransition.fps", @"(_leastBright\w+) = 1\.0;",
            "$1 = 1.0;\n    _leastBrightColor0006 = vec4(0.0);", "1" },
    };

    static string Patch(FmxShader s, string src)
    {
        foreach (var p in Patches)
        {
            if (p[0] != s.Name)
                continue;
            var re = new Regex(p[1]);
            int found = re.Matches(src).Count;
            if (found != int.Parse(p[3]))
                throw new Exception(string.Format("{0}: patch {1} matches {2} times", s.Name, p[1], found));
            src = re.Replace(src, p[2]);
            s.Notes.Add("patched: " + p[1]);
        }
        return src;
    }

    public static void Rewrite(FmxShader s, Dictionary<string, int> varyings)
    {
        bool vertex = s.Kind == "VertexShader";
        string src = Patch(s, Encoding.ASCII.GetString(s.Glsl).Replace("\r\n", "\n"));
        var structs = new Dictionary<string, Struct>();
        foreach (Match m in StructRe.Matches(src))
        {
            var st = new Struct();
            foreach (Match mm in MemberRe.Matches(m.Groups[2].Value))
                st.Members.Add(Tuple.Create(mm.Groups[1].Value, mm.Groups[2].Value,
                    mm.Groups[3].Success ? int.Parse(mm.Groups[3].Value) : 0));
            structs[m.Groups[1].Value] = st;
        }
        var dx = new Dictionary<string, FmxVar>(StringComparer.OrdinalIgnoreCase);
        foreach (var v in s.DxVars)
            dx[v.Name] = v;
        var lines = src.Split('\n').ToList();
        var outLines = new List<string>();
        var uniforms = new List<Tuple<string, string, int>>();
        int blockAt = -1;
        int braceDepth = 0;
        foreach (string raw in lines)
        {
            string line = raw.TrimEnd();
            string t = line.Trim();
            Match m;
            if (braceDepth == 0 && (m = AttributeRe.Match(t)).Success)
            {
                int loc = Array.IndexOf(Attributes, m.Groups[2].Value);
                if (loc < 0)
                    throw new Exception(s.Name + ": attribute " + m.Groups[2].Value);
                s.InputMask |= 1u << loc;
                outLines.Add(string.Format("layout(location = {0}) in {1} {2};", loc, m.Groups[1].Value,
                    m.Groups[2].Value));
            }
            else if (braceDepth == 0 && (m = VaryingRe.Match(t)).Success)
            {
                string name = m.Groups[2].Value;
                int loc;
                if (!varyings.TryGetValue(name, out loc))
                {
                    loc = varyings.Count;
                    varyings[name] = loc;
                }
                outLines.Add(string.Format("layout(location = {0}) {1} {2} {3};", loc, vertex ? "out" : "in",
                    m.Groups[1].Value, name));
            }
            else if (braceDepth == 0 && (m = SamplerRe.Match(t)).Success)
            {
                FmxVar v;
                string name = m.Groups[1].Value.TrimStart('_');
                if (!dx.TryGetValue(name, out v) || v.Kind != "Texture")
                    throw new Exception(s.Name + ": no Direct3D texture unit for " + name);
                outLines.Add(string.Format("layout(binding = {0}) uniform sampler2D {1};", 2 + v.Index,
                    m.Groups[1].Value));
            }
            else if (braceDepth == 0 && (m = UniformRe.Match(t)).Success)
            {
                uniforms.Add(Tuple.Create(m.Groups[1].Value, m.Groups[2].Value,
                    m.Groups[3].Success ? int.Parse(m.Groups[3].Value) : 0));
                if (blockAt < 0)
                    blockAt = outLines.Count;
            }
            else
                outLines.Add(line);
            braceDepth += line.Count(c => c == '{') - line.Count(c => c == '}');
        }

        // The uniform block at the Direct3D offsets.
        var placed = new List<Tuple<int, string>>();
        var globals = new List<string>();
        var inits = new List<string>();
        int end = 0;
        var orphans = new List<Tuple<string, string, int>>();
        foreach (var u in uniforms)
        {
            string name = u.Item2.TrimStart('_');
            var leaves = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
            Leaves(name, u.Item1, u.Item3, structs, leaves, 0);
            int size, align;
            MemberLayout(u.Item1, u.Item3, structs, out size, out align);
            // Where Direct3D has the uniform: its first leaf Direct3D knows.
            int offset = -1;
            foreach (var leaf in leaves)
            {
                FmxVar v;
                if (dx.TryGetValue(leaf.Key, out v))
                {
                    offset = v.Index - leaf.Value;
                    break;
                }
            }
            if (offset < 0)
            {
                orphans.Add(u);
                continue;
            }
            foreach (var leaf in leaves)
            {
                FmxVar v;
                if (dx.TryGetValue(leaf.Key, out v) && v.Index != offset + leaf.Value)
                    throw new Exception(string.Format("{0}: {1} is at {2} in Direct3D, at {3} in the block", s.Name,
                        leaf.Key, v.Index, offset + leaf.Value));
            }
            FmxVar mv;
            if (u.Item1 == "vec4" && dx.TryGetValue(name, out mv) && mv.Kind == "Matrix")
            {
                // FMX's GLES context sets matrices transposed (FMX.Context.GLES.pas:1297), FastCanvas.Context3D as
                // Direct3D takes them: the rows Direct3D has go into the block, and a global of the uniform's name
                // gets their columns in main.
                int rows = Math.Max(1, Math.Min(4, mv.Size / 16));
                int vectors = Math.Max(u.Item3, 1);
                placed.Add(Tuple.Create(offset, string.Format("    layout(offset = {0}) vec4 {1}_rows[{2}];", offset,
                    u.Item2, rows)));
                globals.Add(string.Format("vec4 {0}{1};", u.Item2, u.Item3 > 0 ? "[" + u.Item3 + "]" : ""));
                for (int k = 0; k < vectors && k < 4; k++)
                {
                    var comps = new List<string>();
                    for (int r = 0; r < 4; r++)
                        comps.Add(r < rows ? string.Format("{0}_rows[{1}][{2}]", u.Item2, r, k) : "0.0");
                    inits.Add(string.Format("    {0}{1} = vec4({2});", u.Item2, u.Item3 > 0 ? "[" + k + "]" : "",
                        string.Join(", ", comps)));
                }
                end = Math.Max(end, offset + 16 * rows);
                continue;
            }
            if (offset % align != 0)
            {
                // Direct3D packs a float2 or float3 after a float (offset 4): std140 aligns vectors to 8 and 16. The
                // block takes its components as floats; a global of the uniform's name gets them in main.
                int components = u.Item1 == "vec2" ? 2 : u.Item1 == "vec3" ? 3 : 0;
                if (components == 0 || u.Item3 > 0 || offset % 4 != 0)
                    throw new Exception(string.Format("{0}: {1} at {2} is not aligned to {3}", s.Name, name, offset,
                        align));
                var parts = new List<string>();
                for (int c = 0; c < components; c++)
                {
                    placed.Add(Tuple.Create(offset + 4 * c, string.Format("    layout(offset = {0}) float {1}_{2};",
                        offset + 4 * c, u.Item2, c)));
                    parts.Add(u.Item2 + "_" + c);
                }
                globals.Add(string.Format("{0} {1};", u.Item1, u.Item2));
                inits.Add(string.Format("    {0} = {1}({2});", u.Item2, u.Item1, string.Join(", ", parts)));
                s.Notes.Add(string.Format("{0} at {1}: taken as {2} floats", u.Item2, offset, components));
                end = Math.Max(end, offset + size);
                continue;
            }
            placed.Add(Tuple.Create(offset, string.Format("    layout(offset = {0}) {1} {2}{3};", offset, u.Item1,
                u.Item2, u.Item3 > 0 ? "[" + u.Item3 + "]" : "")));
            end = Math.Max(end, offset + size);
        }
        placed.Sort((a, b) => a.Item1.CompareTo(b.Item1));
        for (int i = 1; i < placed.Count; i++)
            if (placed[i].Item1 == placed[i - 1].Item1)
                throw new Exception(s.Name + ": two uniforms at offset " + placed[i].Item1);
        foreach (var u in orphans)
        {
            int size, align;
            MemberLayout(u.Item1, u.Item3, structs, out size, out align);
            int offset = (end + align - 1) / align * align;
            placed.Add(Tuple.Create(offset, string.Format("    layout(offset = {0}) {1} {2}{3};", offset, u.Item1,
                u.Item2, u.Item3 > 0 ? "[" + u.Item3 + "]" : "")));
            end = offset + size;
            s.Notes.Add(u.Item2 + " has no Direct3D variable: placed at " + offset);
        }
        s.BlockSize = (end + 15) / 16 * 16;
        if (placed.Count > 0)
        {
            var block = new List<string>();
            block.Add(string.Format("layout(std140, binding = {0}) uniform {1}", vertex ? 0 : 1,
                vertex ? "FcVertexConstants" : "FcPixelConstants"));
            block.Add("{");
            block.AddRange(placed.Select(p => p.Item2));
            block.Add("};");
            block.AddRange(globals);
            outLines.InsertRange(blockAt, block);
        }

        string body = string.Join("\n", outLines);
        body = Regex.Replace(body, @"\btexture2D\s*\(", "texture(");
        var head = new StringBuilder();
        head.Append("#version 450\n");
        head.AppendFormat("// FMX shader {0} ({1}), rewritten for Vulkan by tools\\compile-fmx-shaders-vk.ps1\n",
            s.Name, s.Unit);
        string start = "void main()\n{\n";
        if (vertex)
            start += "    gl_PointSize = 1.0;\n";
        foreach (string init in inits)
            start += init + "\n";
        body = Regex.Replace(body, @"void\s+main\s*\(\s*\)\s*\{\n?", start);
        if (!vertex)
        {
            head.Append("layout(location = 0) out vec4 fc_FragColor;\n");
            body = Regex.Replace(body, @"\bgl_FragColor\b", "fc_FragColor");
        }
        s.Vulkan = head + body + "\n";
    }
}
'@
}

function Append-Words([Text.StringBuilder] $Sb, [uint32[]] $Words) {
  for ($i = 0; $i -lt $Words.Length; $i += 10) {
    $k = [Math]::Min(10, $Words.Length - $i)
    $line = ($Words[$i..($i + $k - 1)] | ForEach-Object { '$' + $_.ToString('X8') }) -join ', '
    [void]$Sb.Append('    ' + $line)
    if ($i + $k -lt $Words.Length) { [void]$Sb.AppendLine(',') } else { [void]$Sb.AppendLine(');') }
  }
}

$units = 'FMX.Materials.pas', 'FMX.Materials.Canvas.pas', 'FMX.Filter.pas', 'FMX.Filter.Standard.pas',
  'FMX.Filter.Custom.pas'
$shaders = [Collections.Generic.List[FmxShader]]::new()
foreach ($u in $units) {
  foreach ($s in [FmxGlsl]::Parse($u, [IO.File]::ReadAllText((Join-Path $FmxSource $u)))) { $shaders.Add($s) }
}
$varyings = [Collections.Generic.Dictionary[string, int]]::new()
$tmp = Join-Path ([IO.Path]::GetTempPath()) ('fcfmxvk_' + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory $tmp | Out-Null
$entries = @()
$words = [Collections.Generic.List[uint32]]::new()
try {
  foreach ($s in $shaders) {
    if (-not $s.DxArch) {
      # Without Direct3D bytecode FastCanvas.Context3D does not take the shader (FMX uses it only where the context
      # has fewer than five lights: gouraud1.fvs).
      Write-Host ("{0}: no Direct3D source, skipped" -f $s.Name)
      continue
    }
    [FmxGlsl]::Rewrite($s, $varyings)
    $stage = if ($s.Kind -eq 'VertexShader') { 'vert' } else { 'frag' }
    $file = Join-Path $tmp ("{0}.{1}" -f ($s.Name -replace '[^\w.]', '_'), $stage)
    [IO.File]::WriteAllText($file, $s.Vulkan, [Text.Encoding]::ASCII)
    if ($Dump) {
      New-Item -ItemType Directory -Force $Dump | Out-Null
      Copy-Item $file $Dump
    }
    $spv = "$file.spv"
    # Native tools write to stderr, which PowerShell 5 turns into errors under 'Stop'.
    $ErrorActionPreference = 'Continue'
    $log = & $Glslang -V --target-env vulkan1.2 -S $stage -o $spv $file 2>&1
    $code = $LASTEXITCODE
    if ($code -eq 0 -and $SpirvVal -and (Test-Path $SpirvVal)) {
      $log = & $SpirvVal --target-env vulkan1.2 $spv 2>&1
      if ($LASTEXITCODE -ne 0) { $code = -1 }
    }
    $ErrorActionPreference = 'Stop'
    if ($code -ne 0) {
      $log | ForEach-Object { Write-Host $_ }
      Write-Host $s.Vulkan
      throw "glslangValidator or spirv-val failed for $($s.Name) ($file)"
    }
    $bytes = [IO.File]::ReadAllBytes($spv)
    $first = $words.Count
    for ($i = 0; $i -lt $bytes.Length; $i += 4) { $words.Add([BitConverter]::ToUInt32($bytes, $i)) }
    foreach ($n in $s.Notes) { Write-Host ("{0}: {1}" -f $s.Name, $n) }
    $entries += [pscustomobject]@{
      Name = $s.Name; Kind = $s.Kind; Hash = [FmxGlsl]::Fnv($s.Glsl); Vars = [FmxGlsl]::VarHash($s.DxVars)
      Size = $s.Glsl.Length; Block = $s.BlockSize; Inputs = $s.InputMask; First = $first; Count = $words.Count - $first
    }
  }
  $dup = $entries | Group-Object { '{0}:{1}' -f $_.Hash, $_.Vars } | Where-Object Count -gt 1
  foreach ($d in $dup) {
    $first = $d.Group[0]
    foreach ($e in $d.Group) {
      if ($e.Count -ne $first.Count) { throw "$($e.Name) and $($first.Name): the same source, other SPIR-V" }
    }
  }
  $sb = [Text.StringBuilder]::new()
  [void]$sb.AppendLine('{ Generated by tools\compile-fmx-shaders-vk.ps1 from the GLSL sources of FMX''s shaders')
  [void]$sb.AppendLine('  (' + ($units -join ', ') + '),')
  [void]$sb.AppendLine('  rewritten as Vulkan GLSL 4.50 and compiled to SPIR-V. Do not edit. }')
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine('type')
  [void]$sb.AppendLine('  TVkFmxShader = record')
  [void]$sb.AppendLine('    Name: string;')
  [void]$sb.AppendLine('    /// <summary>FNV-1a of the GLSL source, and of the Direct3D variables (VarHash).</summary>')
  [void]$sb.AppendLine('    Hash, Vars: UInt64;')
  [void]$sb.AppendLine('    Vertex: Boolean;')
  [void]$sb.AppendLine('    /// <summary>Bytes of the uniform block; attribute locations the shader reads; ' +
    'its words in VkFmxWords.')
  [void]$sb.AppendLine('    /// </summary>')
  [void]$sb.AppendLine('    Block: Integer;')
  [void]$sb.AppendLine('    Inputs: Cardinal;')
  [void]$sb.AppendLine('    First, Count: Integer;')
  [void]$sb.AppendLine('  end;')
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine('const')
  [void]$sb.AppendLine(("  VkFmxShaders: array[0..{0}] of TVkFmxShader = (" -f ($entries.Count - 1)))
  for ($i = 0; $i -lt $entries.Count; $i++) {
    $e = $entries[$i]
    $sep = if ($i -lt $entries.Count - 1) { ',' } else { ');' }
    [void]$sb.AppendLine(("    (Name: '{0}'; Hash: `${1:X16}; Vars: `${2:X16};" -f $e.Name, $e.Hash, $e.Vars))
    [void]$sb.AppendLine(("      Vertex: {0}; Block: {1}; Inputs: `${2:X}; First: {3}; Count: {4}){5}" -f
      ($e.Kind -eq 'VertexShader').ToString(), $e.Block, $e.Inputs, $e.First, $e.Count, $sep))
  }
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine(("  VkFmxWords: array[0..{0}] of Cardinal = (" -f ($words.Count - 1)))
  Append-Words $sb $words.ToArray()
  [IO.File]::WriteAllText($Out, $sb.ToString().Replace("`r`n", "`n").Replace("`n", "`r`n"), [Text.Encoding]::ASCII)
  Write-Host ("Wrote {0}: {1} shaders, {2} words, varyings {3}" -f $Out, $entries.Count, $words.Count,
    (($varyings.GetEnumerator() | ForEach-Object { '{0}={1}' -f $_.Key, $_.Value }) -join ' '))
}
finally {
  Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
}
