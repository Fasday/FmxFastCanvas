<#
.SYNOPSIS
  Makes SPIR-V of FMX's own shaders for the Vulkan 3D context: src\Canvas\FastCanvas.VkFmxShaders.inc.

.DESCRIPTION
  FMX ships its material and filter shaders as Direct3D bytecode, Metal and GLSL ES 1.0 sources (generated by Cg) in
  FMX.Materials, FMX.Materials.Canvas, FMX.Filter, FMX.Filter.Standard and FMX.Filter.Custom. This script reads those
  units, takes every shader's GLSL source and its Direct3D variables (DX11, else DX10, else DX11_level_9: the ones
  FastCanvas.Context3D lays the constants out by), and rewrites the GLSL as Vulkan GLSL 4.50:
  - attributes get the locations of TFastContext3DVk (a_Position 0, a_Normal 1, a_Color..a_Color3 2..5,
    a_TexCoord0..3 6..9), varyings one location per name for all shaders (so any vertex and pixel shader pair);
  - the uniforms of a stage go into one std140 block (binding 0: vertex, 1: pixel) at the byte offsets of the Direct3D
    variables of the same names (structures and arrays checked member by member), so the constants FMX sets through
    FastCanvas.Context3D are the same bytes on every backend; uniforms Direct3D does not have go after them;
  - sampler2D uniforms take binding 2 + their Direct3D texture unit;
  - gl_FragColor becomes an output at location 0, texture2D texture, and vertex shaders write gl_PointSize (points).
  Clip space needs no change: the context flips y with the viewport and FMX's projection has Direct3D's depth range.
  The result is compiled with glslangValidator and validated with spirv-val (Vulkan SDK) and written as one array of
  SPIR-V words with a table keyed by an FNV-1a hash of the GLSL source and one of the Direct3D variables (name, kind,
  offset, size): TFastContext3DVk finds the SPIR-V of a TContextShader by them, and reports shaders without one
  (application shaders) as not supported.

.EXAMPLE
  .\tools\compile-fmx-shaders-vk.ps1
#>
