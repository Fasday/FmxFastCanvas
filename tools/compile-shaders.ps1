<#
.SYNOPSIS
  Compiles the shaders of src\Canvas\Shaders into Pascal includes:
  - FastCanvas.hlsl and FastOutput.hlsl with fxc (vs_4_0 / ps_4_0) into src\Canvas\FastCanvas.Shaders.inc, and with
    the Vulkan SDK's dxc into SPIR-V, src\Canvas\FastCanvas.VkShaders.inc (validated by spirv-val);
  - FastRay.hlsl with dxc (shader model 6.5, inline ray queries) into src\Canvas\FastCanvas.RayShaders.inc, and as
    SPIR-V (Vulkan 1.2, ray queries) into src\Canvas\FastCanvas.VkRayShaders.inc;
  - FastDlss.hlsl with fxc (vs_5_0 / ps_5_0) into src\Canvas\FastCanvas.DlssShaders.inc;
  - FMX's own shaders as SPIR-V for the Vulkan 3D context (tools\compile-fmx-shaders-vk.ps1) into
    src\Canvas\FastCanvas.VkFmxShaders.inc.

.DESCRIPTION
  The generated includes hold the bytecode as Pascal byte arrays, so building the canvas needs neither the compilers
  nor their DLLs. Run after every change of the HLSL and commit the includes. fxc and dxc come with the Windows SDK;
  the newest x64 ones under "Windows Kits\10\bin" are used unless -Fxc / -Dxc are given. dxc signs the DXIL with
  dxil.dll from its folder (Direct3D 12 rejects unsigned DXIL).

  Application ray passes (TFastContext3D12.RayDispatch / RayDraw) are compiled the same way by the application, with
  src\Canvas\Shaders as an include folder (FastRayApp.hlsli): dxc -T cs_6_5 -E <entry> -I src\Canvas\Shaders ...

.EXAMPLE
  .\tools\compile-shaders.ps1
#>
param(
  [string] $Fxc = '',
  [string] $Dxc = '',
  # dxc with SPIR-V code generation (the one of the Vulkan SDK; the Windows SDK's has none) and spirv-val, for the
  # Vulkan back end: src\Canvas\FastCanvas.VkShaders.inc. Without them that include is left as it is.
  [string] $DxcSpirv = '',
  [string] $SpirvVal = ''
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$kits = 'C:\Program Files (x86)\Windows Kits\10\bin'

function Find-Tool([string] $Name) {
  $p = Get-ChildItem $kits -Recurse -Filter $Name -ErrorAction SilentlyContinue |
    Where-Object { $_.Directory.Name -eq 'x64' } | Sort-Object { $_.Directory.Parent.Name } | Select-Object -Last 1 -ExpandProperty FullName
  if (-not $p) { throw "$Name not found under $kits" }
  $p
}

function Append-Bytes([Text.StringBuilder] $Sb, [string] $Name, [byte[]] $Bytes) {
  [void]$Sb.AppendLine(("  {0}: array[0..{1}] of Byte = (" -f $Name, ($Bytes.Length - 1)))
  for ($i = 0; $i -lt $Bytes.Length; $i += 24) {
    $n = [Math]::Min(24, $Bytes.Length - $i)
    $line = ($Bytes[$i..($i + $n - 1)] | ForEach-Object { '$' + $_.ToString('X2') }) -join ', '
    if ($i + $n -lt $Bytes.Length) { $line += ',' } else { $line += ');' }
    [void]$Sb.AppendLine('    ' + $line)
  }
  [void]$Sb.AppendLine('')
  Write-Host ("{0}: {1} bytes" -f $Name, $Bytes.Length)
}

function Append-Words([Text.StringBuilder] $Sb, [string] $Name, [byte[]] $Bytes) {
  # SPIR-V as 32-bit words: vkCreateShaderModule wants its code aligned to 4 bytes.
  if ($Bytes.Length % 4 -ne 0) { throw "$Name is not a whole number of 32-bit words" }
  $n = $Bytes.Length / 4
  [void]$Sb.AppendLine(("  {0}: array[0..{1}] of Cardinal = (" -f $Name, ($n - 1)))
  for ($i = 0; $i -lt $n; $i += 10) {
    $k = [Math]::Min(10, $n - $i)
    $line = (0..($k - 1) | ForEach-Object { '$' + [BitConverter]::ToUInt32($Bytes, 4 * ($i + $_)).ToString('X8') }) -join ', '
    if ($i + $k -lt $n) { $line += ',' } else { $line += ');' }
    [void]$Sb.AppendLine('    ' + $line)
  }
  [void]$Sb.AppendLine('')
  Write-Host ("{0}: {1} bytes" -f $Name, $Bytes.Length)
}

if (-not $Fxc) { $Fxc = Find-Tool 'fxc.exe' }
if (-not $Dxc) { $Dxc = Find-Tool 'dxc.exe' }

$tmp = Join-Path ([IO.Path]::GetTempPath()) ('fcshaders_' + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory $tmp | Out-Null
try {
  # Canvas shaders (fxc, DXBC: Direct3D 11 and 12).
  $src = Join-Path $root 'src\Canvas\Shaders\FastCanvas.hlsl'
  $out = Join-Path $root 'src\Canvas\FastCanvas.Shaders.inc'
  $sb = [Text.StringBuilder]::new()
  [void]$sb.AppendLine('{ Generated by tools\compile-shaders.ps1 from src\Canvas\Shaders\FastCanvas.hlsl. Do not edit. }')
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine('const')
  $outputSrc = Join-Path $root 'src\Canvas\Shaders\FastOutput.hlsl'
  foreach ($e in @(
    @{ Name = 'FastCanvasVS'; Entry = 'VSMain'; Profile = 'vs_4_0'; Src = $src },
    @{ Name = 'FastCanvasPS'; Entry = 'PSMain'; Profile = 'ps_4_0'; Src = $src },
    @{ Name = 'FastCanvasPSLinear'; Entry = 'PSMainLinear'; Profile = 'ps_4_0'; Src = $src },
    @{ Name = 'FastCanvasPSDual'; Entry = 'PSMainDual'; Profile = 'ps_4_0'; Src = $src },
    @{ Name = 'FastOutputVS'; Entry = 'VSOutput'; Profile = 'vs_4_0'; Src = $outputSrc },
    @{ Name = 'FastOutputPS'; Entry = 'PSOutput'; Profile = 'ps_4_0'; Src = $outputSrc })) {
    $cso = Join-Path $tmp ($e.Name + '.cso')
    & $Fxc /nologo /T $e.Profile /E $e.Entry /O3 /WX /Fo $cso $e.Src
    if ($LASTEXITCODE -ne 0) { throw "fxc failed for $($e.Entry)" }
    Append-Bytes $sb $e.Name ([IO.File]::ReadAllBytes($cso))
  }
  [IO.File]::WriteAllText($out, $sb.ToString(), [Text.Encoding]::ASCII)
  Write-Host "Wrote $out"

  # Canvas shaders for Vulkan (dxc, SPIR-V 1.3: Vulkan 1.1 and up). Bindings: b0.. at 0, t0.. at 16, s0.. at 32 (one
  # descriptor set); constant buffers in the Direct3D layout, so the records of the back ends are shared. HLSL 2018:
  # the sRGB curves select per component with the ternary operator. The clip-space y is flipped by the viewport.
  # The variants of PSMain for blending draws (TGpuVkVariant in FastCanvas.GpuVk): only the WITH_ switches listed are
  # on; they and the ...Flat shaders are compiled with FLAT_TABLES (the vertex shader hands the instance's paint and
  # clip table entries to the pixel shader), the others without. ...Z vertex shaders: WITH_DEPTH (targets with a depth
  # buffer for opaque interiors); VSMesh: paths drawn as triangles; VSInterior, PSInterior: the opaque interiors.
  $vkSdk = [Environment]::GetEnvironmentVariable('VULKAN_SDK', 'Machine')
  if (-not $DxcSpirv -and $vkSdk) { $DxcSpirv = Join-Path $vkSdk 'Bin\dxc.exe' }
  if (-not $SpirvVal -and $vkSdk) { $SpirvVal = Join-Path $vkSdk 'Bin\spirv-val.exe' }
  $switches = @('WITH_SHAPES', 'WITH_DASHES', 'WITH_IMAGES', 'WITH_GLYPHS', 'WITH_CLEARTYPE', 'WITH_PATHS',
    'WITH_GRADIENTS', 'WITH_BRUSHES', 'WITH_CLIPS')
  function Variant([string[]] $On) {
    $d = @()
    foreach ($s in $switches) { $d += @('-D', ('{0}={1}' -f $s, [int]($On -contains $s))) }
    $d += @('-D', 'FLAT_TABLES=1')
    , $d
  }
  if ($DxcSpirv -and (Test-Path $DxcSpirv)) {
    $out = Join-Path $root 'src\Canvas\FastCanvas.VkShaders.inc'
    $sb = [Text.StringBuilder]::new()
    [void]$sb.AppendLine('{ Generated by tools\compile-shaders.ps1 from src\Canvas\Shaders\FastCanvas.hlsl and FastOutput.hlsl')
    [void]$sb.AppendLine('  (SPIR-V for the Vulkan back end). Do not edit. }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('const')
    $shapes = @('WITH_SHAPES', 'WITH_GRADIENTS')
    $ui = @('WITH_SHAPES', 'WITH_GRADIENTS', 'WITH_GLYPHS', 'WITH_IMAGES')
    $paths = @('WITH_SHAPES', 'WITH_GRADIENTS', 'WITH_PATHS')
    foreach ($e in @(
      @{ Name = 'FastCanvasVkVS'; Entry = 'VSMain'; Profile = 'vs_6_0'; Src = $src; Defines = @() },
      @{ Name = 'FastCanvasVkPS'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src; Defines = @() },
      @{ Name = 'FastCanvasVkVSFlat'; Entry = 'VSMain'; Profile = 'vs_6_0'; Src = $src; Defines = @('-D', 'FLAT_TABLES=1') },
      @{ Name = 'FastCanvasVkPSFlat'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src; Defines = @('-D', 'FLAT_TABLES=1') },
      @{ Name = 'FastCanvasVkPSShapes'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src; Defines = (Variant $shapes) },
      @{ Name = 'FastCanvasVkPSShapesClip'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src;
        Defines = (Variant ($shapes + 'WITH_CLIPS')) },
      @{ Name = 'FastCanvasVkPSGlyphs'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src; Defines = (Variant 'WITH_GLYPHS') },
      @{ Name = 'FastCanvasVkPSGlyphsClip'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src;
        Defines = (Variant 'WITH_GLYPHS', 'WITH_CLIPS') },
      @{ Name = 'FastCanvasVkPSImages'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src; Defines = (Variant 'WITH_IMAGES') },
      @{ Name = 'FastCanvasVkPSImagesClip'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src;
        Defines = (Variant 'WITH_IMAGES', 'WITH_CLIPS') },
      @{ Name = 'FastCanvasVkPSUi'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src; Defines = (Variant $ui) },
      @{ Name = 'FastCanvasVkPSUiClip'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src;
        Defines = (Variant ($ui + 'WITH_CLIPS')) },
      @{ Name = 'FastCanvasVkPSPaths'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src; Defines = (Variant $paths) },
      @{ Name = 'FastCanvasVkPSPathsClip'; Entry = 'PSMain'; Profile = 'ps_6_0'; Src = $src;
        Defines = (Variant ($paths + 'WITH_CLIPS')) },
      @{ Name = 'FastCanvasVkVSFlatZ'; Entry = 'VSMain'; Profile = 'vs_6_0'; Src = $src;
        Defines = @('-D', 'FLAT_TABLES=1', '-D', 'WITH_DEPTH=1') },
      @{ Name = 'FastCanvasVkVSMeshZ'; Entry = 'VSMesh'; Profile = 'vs_6_0'; Src = $src;
        Defines = @('-D', 'FLAT_TABLES=1', '-D', 'WITH_DEPTH=1') },
      @{ Name = 'FastCanvasVkVSInterior'; Entry = 'VSInterior'; Profile = 'vs_6_0'; Src = $src; Defines = @() },
      @{ Name = 'FastCanvasVkPSInterior'; Entry = 'PSInterior'; Profile = 'ps_6_0'; Src = $src; Defines = @() },
      @{ Name = 'FastCanvasVkPSLinear'; Entry = 'PSMainLinear'; Profile = 'ps_6_0'; Src = $src; Defines = @() },
      @{ Name = 'FastCanvasVkPSDual'; Entry = 'PSMainDual'; Profile = 'ps_6_0'; Src = $src; Defines = @() },
      @{ Name = 'FastOutputVkVS'; Entry = 'VSOutput'; Profile = 'vs_6_0'; Src = $outputSrc; Defines = @() },
      @{ Name = 'FastOutputVkPS'; Entry = 'PSOutput'; Profile = 'ps_6_0'; Src = $outputSrc; Defines = @() })) {
      $spv = Join-Path $tmp ($e.Name + '.spv')
      & $DxcSpirv -nologo -spirv -HV 2018 '-fspv-target-env=vulkan1.1' -fvk-use-dx-layout -fvk-b-shift 0 0 `
        -fvk-t-shift 16 0 -fvk-s-shift 32 0 -fvk-u-shift 48 0 -T $e.Profile -E $e.Entry -O3 -WX @($e.Defines) -Fo $spv `
        $e.Src
      if ($LASTEXITCODE -ne 0) { throw "dxc (SPIR-V) failed for $($e.Name)" }
      if ($SpirvVal -and (Test-Path $SpirvVal)) {
        & $SpirvVal --target-env vulkan1.1 $spv
        if ($LASTEXITCODE -ne 0) { throw "spirv-val failed for $($e.Name)" }
      }
      Append-Words $sb $e.Name ([IO.File]::ReadAllBytes($spv))
    }
    [IO.File]::WriteAllText($out, $sb.ToString(), [Text.Encoding]::ASCII)
    Write-Host "Wrote $out"
  } else {
    Write-Warning 'dxc with SPIR-V not found (Vulkan SDK): src\Canvas\FastCanvas.VkShaders.inc not regenerated'
  }

  # Ray-traced effects (dxc, DXIL, shader model 6.5).
  $src = Join-Path $root 'src\Canvas\Shaders\FastRay.hlsl'
  $out = Join-Path $root 'src\Canvas\FastCanvas.RayShaders.inc'
  $sb = [Text.StringBuilder]::new()
  [void]$sb.AppendLine('{ Generated by tools\compile-shaders.ps1 from src\Canvas\Shaders\FastRay.hlsl. Do not edit. }')
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine('const')
  foreach ($e in @(
    @{ Name = 'FastRayVS'; Entry = 'VSMain'; Profile = 'vs_6_5'; Defines = @() },
    @{ Name = 'FastRayPS'; Entry = 'PSRay'; Profile = 'ps_6_5'; Defines = @() },
    @{ Name = 'FastRayPSMS'; Entry = 'PSRay'; Profile = 'ps_6_5'; Defines = @('-D', 'MULTISAMPLE=1') },
    @{ Name = 'FastHalfPS'; Entry = 'PSHalf'; Profile = 'ps_6_5'; Defines = @() },
    @{ Name = 'FastHalfPSMS'; Entry = 'PSHalf'; Profile = 'ps_6_5'; Defines = @('-D', 'MULTISAMPLE=1') },
    @{ Name = 'FastBlurPS'; Entry = 'PSBlur'; Profile = 'ps_6_5'; Defines = @() },
    @{ Name = 'FastBlurPSMS'; Entry = 'PSBlur'; Profile = 'ps_6_5'; Defines = @('-D', 'MULTISAMPLE=1') },
    @{ Name = 'FastReflectPS'; Entry = 'PSReflect'; Profile = 'ps_6_5'; Defines = @() },
    @{ Name = 'FastReflectPSMS'; Entry = 'PSReflect'; Profile = 'ps_6_5'; Defines = @('-D', 'MULTISAMPLE=1') })) {
    $cso = Join-Path $tmp ($e.Name + '.cso')
    & $Dxc -nologo -T $e.Profile -E $e.Entry -O3 -WX @($e.Defines) -Fo $cso $src
    if ($LASTEXITCODE -ne 0) { throw "dxc failed for $($e.Name)" }
    Append-Bytes $sb $e.Name ([IO.File]::ReadAllBytes($cso))
  }
  [IO.File]::WriteAllText($out, $sb.ToString(), [Text.Encoding]::ASCII)
  Write-Host "Wrote $out"

  # Ray-traced effects for the Vulkan 3D context (dxc, SPIR-V with ray queries, Vulkan 1.2): set 0 binding 0 the
  # constants (Direct3D layout), t0..t3 at 16..19 (scene, depth, factor, instance records), s0 at 32; the geometries
  # (space 1) and textures (space 2) as runtime arrays at binding 16 of sets 1 and 2.
  if ($DxcSpirv -and (Test-Path $DxcSpirv)) {
    $out = Join-Path $root 'src\Canvas\FastCanvas.VkRayShaders.inc'
    $sb = [Text.StringBuilder]::new()
    [void]$sb.AppendLine('{ Generated by tools\compile-shaders.ps1 from src\Canvas\Shaders\FastRay.hlsl (SPIR-V for the Vulkan 3D')
    [void]$sb.AppendLine('  context). Do not edit. }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('const')
    foreach ($e in @(
      @{ Name = 'FastRayVkVS'; Entry = 'VSMain'; Profile = 'vs_6_5'; Defines = @() },
      @{ Name = 'FastRayVkPS'; Entry = 'PSRay'; Profile = 'ps_6_5'; Defines = @() },
      @{ Name = 'FastRayVkPSMS'; Entry = 'PSRay'; Profile = 'ps_6_5'; Defines = @('-D', 'MULTISAMPLE=1') },
      @{ Name = 'FastHalfVkPS'; Entry = 'PSHalf'; Profile = 'ps_6_5'; Defines = @() },
      @{ Name = 'FastHalfVkPSMS'; Entry = 'PSHalf'; Profile = 'ps_6_5'; Defines = @('-D', 'MULTISAMPLE=1') },
      @{ Name = 'FastBlurVkPS'; Entry = 'PSBlur'; Profile = 'ps_6_5'; Defines = @() },
      @{ Name = 'FastBlurVkPSMS'; Entry = 'PSBlur'; Profile = 'ps_6_5'; Defines = @('-D', 'MULTISAMPLE=1') },
      @{ Name = 'FastReflectVkPS'; Entry = 'PSReflect'; Profile = 'ps_6_5'; Defines = @() },
      @{ Name = 'FastReflectVkPSMS'; Entry = 'PSReflect'; Profile = 'ps_6_5'; Defines = @('-D', 'MULTISAMPLE=1') })) {
      $spv = Join-Path $tmp ($e.Name + '.spv')
      & $DxcSpirv -nologo -spirv '-fspv-target-env=vulkan1.2' -fvk-use-dx-layout -fvk-b-shift 0 0 -fvk-t-shift 16 0 `
        -fvk-t-shift 16 1 -fvk-t-shift 16 2 -fvk-s-shift 32 0 -T $e.Profile -E $e.Entry -O3 -WX @($e.Defines) -Fo $spv `
        (Join-Path $root 'src\Canvas\Shaders\FastRay.hlsl')
      if ($LASTEXITCODE -ne 0) { throw "dxc (SPIR-V) failed for $($e.Name)" }
      if ($SpirvVal -and (Test-Path $SpirvVal)) {
        & $SpirvVal --target-env vulkan1.2 $spv
        if ($LASTEXITCODE -ne 0) { throw "spirv-val failed for $($e.Name)" }
      }
      Append-Words $sb $e.Name ([IO.File]::ReadAllBytes($spv))
    }
    [IO.File]::WriteAllText($out, $sb.ToString(), [Text.Encoding]::ASCII)
    Write-Host "Wrote $out"
  }

  # DLSS inputs and output of the Direct3D 12 3D context (fxc, DXBC, shader model 5.0).
  $src = Join-Path $root 'src\Canvas\Shaders\FastDlss.hlsl'
  $out = Join-Path $root 'src\Canvas\FastCanvas.DlssShaders.inc'
  $sb = [Text.StringBuilder]::new()
  [void]$sb.AppendLine('{ Generated by tools\compile-shaders.ps1 from src\Canvas\Shaders\FastDlss.hlsl. Do not edit. }')
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine('const')
  foreach ($e in @(
    @{ Name = 'DlssVSMotion'; Entry = 'VSMotion'; Profile = 'vs_5_0' },
    @{ Name = 'DlssPSMotion'; Entry = 'PSMotion'; Profile = 'ps_5_0' },
    @{ Name = 'DlssVSFull'; Entry = 'VSFull'; Profile = 'vs_5_0' },
    @{ Name = 'DlssPSCopy'; Entry = 'PSCopy'; Profile = 'ps_5_0' },
    @{ Name = 'DlssPSDepth'; Entry = 'PSDepth'; Profile = 'ps_5_0' },
    @{ Name = 'DlssPSResolve'; Entry = 'PSResolve'; Profile = 'ps_5_0' },
    @{ Name = 'DlssPSEmulate'; Entry = 'PSEmulate'; Profile = 'ps_5_0' },
    @{ Name = 'DlssPSFill'; Entry = 'PSFill'; Profile = 'ps_5_0' })) {
    $cso = Join-Path $tmp ($e.Name + '.cso')
    & $Fxc /nologo /T $e.Profile /E $e.Entry /O3 /WX /Fo $cso $src
    if ($LASTEXITCODE -ne 0) { throw "fxc failed for $($e.Entry)" }
    Append-Bytes $sb $e.Name ([IO.File]::ReadAllBytes($cso))
  }
  [IO.File]::WriteAllText($out, $sb.ToString(), [Text.Encoding]::ASCII)
  Write-Host "Wrote $out"

  # FMX's own shaders for the Vulkan 3D context (GLSL from FMX's sources, glslangValidator of the Vulkan SDK).
  $glslang = if ($vkSdk) { Join-Path $vkSdk 'Bin\glslangValidator.exe' } else { '' }
  if ($glslang -and (Test-Path $glslang)) {
    & (Join-Path $PSScriptRoot 'compile-fmx-shaders-vk.ps1') -Glslang $glslang -SpirvVal $SpirvVal
  } else {
    Write-Warning 'glslangValidator not found (Vulkan SDK): src\Canvas\FastCanvas.VkFmxShaders.inc not regenerated'
  }
}
finally {
  Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
}
