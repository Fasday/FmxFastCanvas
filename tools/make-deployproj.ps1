<#
.SYNOPSIS
  Writes the .deployproj of an FMX project for Android64, which msbuild's Deploy target needs to package the APK.

.DESCRIPTION
  The IDE writes <Project>.deployproj when it deploys; a command-line build has none. This script writes the same
  items for Android64 (the library, the generated manifest and resources, the launcher, splash and notification
  images of the IDE's artwork) for the given configurations, and copies AndroidManifest.template.xml (the IDE's
  template from %APPDATA%) next to the project when it is missing.

.EXAMPLE
  .\tools\make-deployproj.ps1 -Project src\Probe\PortProbe.dproj
#>
param(
  [Parameter(Mandatory = $true)] [string] $Project,
  [string[]] $Config = @('Release', 'Debug')
)

$ErrorActionPreference = 'Stop'

$ProjectPath = (Resolve-Path $Project).Path
$Dir = Split-Path $ProjectPath
$Name = [IO.Path]::GetFileNameWithoutExtension($ProjectPath)

$Template = Join-Path $Dir 'AndroidManifest.template.xml'
if (-not (Test-Path $Template)) {
  Copy-Item (Join-Path $env:APPDATA 'Embarcadero\BDS\37.0\AndroidManifest.xml') $Template
}

$Art = '$(BDS)\bin\Artwork\Android'
# Local file, remote directory under the APK root, remote name, deploy class, required.
$Files = @(
  @("$Art\FM_LauncherIcon_36x36.png", 'res\drawable-ldpi', 'ic_launcher.png', 'Android_LauncherIcon36', $false),
  @("$Art\FM_LauncherIcon_48x48.png", 'res\drawable-mdpi', 'ic_launcher.png', 'Android_LauncherIcon48', $false),
  @("$Art\FM_LauncherIcon_72x72.png", 'res\drawable-hdpi', 'ic_launcher.png', 'Android_LauncherIcon72', $false),
  @("$Art\FM_LauncherIcon_96x96.png", 'res\drawable-xhdpi', 'ic_launcher.png', 'Android_LauncherIcon96', $false),
  @("$Art\FM_LauncherIcon_144x144.png", 'res\drawable-xxhdpi', 'ic_launcher.png', 'Android_LauncherIcon144', $false),
  @("$Art\FM_LauncherIcon_192x192.png", 'res\drawable-xxxhdpi', 'ic_launcher.png', 'Android_LauncherIcon192', $false),
  @("$Art\FM_NotificationIcon_24x24.png", 'res\drawable-mdpi', 'ic_notification.png', 'Android_NotificationIcon24', $false),
  @("$Art\FM_NotificationIcon_36x36.png", 'res\drawable-hdpi', 'ic_notification.png', 'Android_NotificationIcon36', $false),
  @("$Art\FM_NotificationIcon_48x48.png", 'res\drawable-xhdpi', 'ic_notification.png', 'Android_NotificationIcon48', $false),
  @("$Art\FM_NotificationIcon_72x72.png", 'res\drawable-xxhdpi', 'ic_notification.png', 'Android_NotificationIcon72', $false),
  @("$Art\FM_NotificationIcon_96x96.png", 'res\drawable-xxxhdpi', 'ic_notification.png', 'Android_NotificationIcon96', $false),
  @("$Art\FM_SplashImage_426x320.png", 'res\drawable-small', 'splash_image.png', 'Android_SplashImage426', $false),
  @("$Art\FM_SplashImage_470x320.png", 'res\drawable-normal', 'splash_image.png', 'Android_SplashImage470', $false),
  @("$Art\FM_SplashImage_640x480.png", 'res\drawable-large', 'splash_image.png', 'Android_SplashImage640', $false),
  @("$Art\FM_SplashImage_960x720.png", 'res\drawable-xlarge', 'splash_image.png', 'Android_SplashImage960', $false)
)
# Generated by the build into the output directory of the configuration.
$Generated = @(
  @('splash_image_def.xml', 'res\drawable', 'splash_image_def.xml', 'AndroidSplashImageDef', $false),
  @('styles.xml', 'res\values', 'styles.xml', 'AndroidSplashStyles', $false),
  @('styles-v21.xml', 'res\values-v21', 'styles.xml', 'AndroidSplashStylesV21', $false),
  @('styles-v35.xml', 'res\values-v35', 'styles.xml', 'AndroidSplashStylesV35', $false),
  @('strings.xml', 'res\values', 'strings.xml', 'Android_Strings', $false),
  @('colors.xml', 'res\values', 'colors.xml', 'Android_Colors', $false),
  @('colors-night-v21.xml', 'res\values-night-v21', 'colors.xml', 'Android_ColorsDark', $false),
  @('AndroidManifest.xml', '', 'AndroidManifest.xml', 'ProjectAndroidManifest', $false),
  @("lib$Name.so", 'library\lib\arm64-v8a', "lib$Name.so", 'ProjectOutput', $true)
)

function Item([string] $Local, [string] $Cfg, [string] $RemoteDir, [string] $RemoteName, [string] $Class,
  [bool] $Required) {
  $remote = if ($RemoteDir) { "$Name\$RemoteDir\" } else { "$Name\" }
  $lines = @(
    "        <DeployFile Include=`"$Local`" Condition=`"'`$(Config)'=='$Cfg'`">",
    "            <RemoteDir>$remote</RemoteDir>",
    "            <RemoteName>$RemoteName</RemoteName>",
    "            <DeployClass>$Class</DeployClass>",
    '            <Operation>1</Operation>',
    '            <LocalCommand/>',
    '            <RemoteCommand/>',
    '            <Overwrite>True</Overwrite>'
  )
  if ($Required) { $lines += '            <Required>True</Required>' }
  $lines += '        </DeployFile>'
  return $lines
}

$out = @(
  '<?xml version="1.0" encoding="utf-8"?>',
  '<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">',
  '    <Import Condition="Exists(''$(BDS)\bin\CodeGear.Deployment.targets'')" Project="$(BDS)\bin\CodeGear.Deployment.targets"/>',
  '    <ProjectExtensions>',
  '        <ProjectFileVersion>12</ProjectFileVersion>',
  '    </ProjectExtensions>',
  '    <PropertyGroup>',
  '        <DeviceId Condition="''$(Platform)''==''Android64''"></DeviceId>',
  '    </PropertyGroup>',
  '    <ItemGroup Condition="''$(Platform)''==''Android64''">'
)
foreach ($cfg in $Config) {
  foreach ($f in $Files) { $out += Item $f[0] $cfg $f[1] $f[2] $f[3] $f[4] }
  foreach ($f in $Generated) { $out += Item "Android64\$cfg\$($f[0])" $cfg $f[1] $f[2] $f[3] $f[4] }
}
$out += '    </ItemGroup>'
$out += '</Project>'

$Target = Join-Path $Dir "$Name.deployproj"
[IO.File]::WriteAllText($Target, ($out -join "`r`n") + "`r`n", (New-Object Text.UTF8Encoding($false)))
Write-Host "OK -> $Target"
