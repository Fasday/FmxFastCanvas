<#
.SYNOPSIS
  Command-line build of a Delphi (FMX) program for Win64 with dcc64.

.DESCRIPTION
  - Output exe/map:  bin\Win64\<Config>\
  - DCU:             dcu\Win64\<Config>\<ProjectName>\
  - Compiles res\WinApp.rc (PerMonitorV2 manifest) to dcu\WinApp.res; add {$R WinApp.res} to the .dpr.
  - Copies sk4d.dll (Skia) next to the exe, required for the Skia canvases.
  - Always a full build (-B) so that changed compiler switches are never mixed with stale DCUs.
  - Detailed .map (-GD) is generated for profilers (map2pdb, WPA).
  - Generates dcu\BuildInfo.inc (commit, dirty flag, compiler version, config) for {$I BuildInfo.inc}.

.EXAMPLE
  .\build.ps1 -Project src\Bench\FmxCanvasBench.dpr
  .\build.ps1 -Project src\Bench\FmxCanvasBench.dpr -Config Debug -SearchPath src\Common -Define BENCH_TRACE
#>
param(
  [Parameter(Mandatory = $true)] [string] $Project,
  [ValidateSet('Release', 'Debug')] [string] $Config = 'Release',
  [string[]] $SearchPath = @(),
  [string[]] $Define = @(),
  # Output root instead of bin\ (e.g. bin-dev to build while a benchmark run uses bin\).
  [string] $OutRoot = 'bin'
)

$ErrorActionPreference = 'Stop'

$Bds = 'C:\Program Files (x86)\Embarcadero\Studio\37.0'   # Delphi 13.2 (37.0.60952.8797)
$Dcc = Join-Path $Bds 'bin\dcc64.exe'
$Brcc = Join-Path $Bds 'bin\brcc32.exe'
$Root = $PSScriptRoot

$ProjectPath = (Resolve-Path $Project).Path
$Name = [IO.Path]::GetFileNameWithoutExtension($ProjectPath)
$OutDir = Join-Path $Root "$OutRoot\Win64\$Config"
$DcuDir = Join-Path $Root "dcu\$OutRoot\Win64\$Config\$Name"
$ResDir = Join-Path $Root 'dcu'
New-Item -ItemType Directory -Force -Path $OutDir, $DcuDir | Out-Null

# Same environment as rsvars.bat
$env:BDS = $Bds
$env:BDSINCLUDE = Join-Path $Bds 'include'
$env:BDSCOMMONDIR = 'C:\Users\Public\Documents\Embarcadero\Studio\37.0'

# 1. Shared resources (manifest)
$Rc = Join-Path $Root 'res\WinApp.rc'
$Res = Join-Path $ResDir 'WinApp.res'
Push-Location (Join-Path $Root 'res')
try {
  & $Brcc -fo"$Res" "$Rc" | Out-Null
  if ($LASTEXITCODE -ne 0) { throw "brcc32 failed ($LASTEXITCODE)" }
} finally { Pop-Location }

# 2. Build info (commit, dirty flag over the inputs of the binary, compiler version)
$commit = 'unknown'
$dirty = 'True'
Push-Location $Root
# Outside a git work tree (a source archive, a repository without commits) the commit stays unknown.
$eap = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
try {
  $c = & git rev-parse --short=12 HEAD 2>$null
  if ($LASTEXITCODE -eq 0 -and $c) {
    $commit = "$c".Trim()
    $changes = & git status --porcelain -- src res third_party build.ps1 2>$null
    $dirty = if ($changes) { 'True' } else { 'False' }
  }
} catch {
} finally {
  $ErrorActionPreference = $eap
  Pop-Location
}
$dccVersion = (Get-Item $Dcc).VersionInfo.FileVersion
$buildInfo = @(
  '// Generated by build.ps1. Do not edit.',
  'const',
  "  BuildCommit = '$commit';",
  "  BuildDirty = $dirty;",
  "  BuildCompilerVersion = '$dccVersion';",
  "  BuildConfig = '$Config';"
)
Set-Content -Path (Join-Path $ResDir 'BuildInfo.inc') -Value $buildInfo -Encoding ascii

# 3. Compiler switches
$paths = @($ResDir) + ($SearchPath | ForEach-Object { (Resolve-Path $_).Path })
# Direct3D 12 headers (FastCanvas.Device, FastCanvas.Gpu12).
$paths += Join-Path $Root 'third_party\delphidx12\src'
$defines = @($Define)
$pathArg = ($paths -join ';')
$flags = @(
  '-B', '-Q',
  '-NSSystem;Winapi;FMX;System.Win;Data;Xml',
  "-E$OutDir", "-NU$DcuDir",
  "-U$pathArg", "-I$pathArg", "-R$pathArg",
  '-GD'                        # detailed map file
)
if ($Config -eq 'Release') {
  $flags += '-$O+', '-$C-', '-$D+', '-$L+', '-$W-'   # optimized; debug info only for map/symbols
  $defines += 'RELEASE'
} else {
  $flags += '-$O-', '-$C+', '-$D+', '-$L+', '-$W+', '-V'
  $defines += 'DEBUG'
}
$flags += '-D' + ($defines -join ';')

# 4. Compile
Write-Host "dcc64 $Name [$Config] commit $commit dirty=$dirty"
& $Dcc @flags $ProjectPath
if ($LASTEXITCODE -ne 0) { throw "dcc64 failed ($LASTEXITCODE)" }

# 5. Runtime dependencies
$Sk4d = Join-Path $Bds 'Redist\win64\sk4d.dll'
Copy-Item $Sk4d $OutDir -Force

Write-Host "OK -> $(Join-Path $OutDir "$Name.exe")"
